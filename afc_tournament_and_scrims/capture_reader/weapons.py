"""What gun a kill was made with, in words (owner, 2 Nov 2026, AFC inbox #468: "find out what exact weapons they are
using nd not just the codes they are showing").

The debugger log names a kill's weapon by number (``OnGameAchievementNotify ... weapon:N``, read by tailer.py).
weapons_table.py names 253 of them as the GAME shows them to players (814 Skorp, 812 Hawk, 45 M82B, 21002 M590),
generated by dev/build_weapons.py from the client's own English text (1.5.3; owner, 3 Nov 2026, AFC inbox #474:
"EVO3 and SeaGull are not the actual names of the guns please"). A number the table does not hold (80006 ...)
reads as "unknown gun (id N)", never as a bare number or an internal label. A negative number is the zone, a fall
or a bleed-out, not a gun.

CONNECTS TO: tailer.py (names the weapon on each kill.detail event it emits), dashboard.py / assets/dashboard.html
(prints the name in the kills feed). The website's seed_game_weapons reads the same enum (AFC-B kill_feed.py).
"""
from __future__ import annotations

from typing import Optional

from .weapons_table import WEAPON_NAMES


def weapon_label(weapon_id) -> Optional[str]:
    """The name to show for a kill's weapon id, "unknown gun (id N)" for an id the table does not know, or None
    when there is no gun to name (no id, or a negative id: zone, fall, bleed-out)."""
    try:
        wid = int(weapon_id)
    except (TypeError, ValueError):
        return None
    if wid < 0:
        return None
    return WEAPON_NAMES.get(wid) or f"unknown gun (id {wid})"
