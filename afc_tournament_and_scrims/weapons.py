"""What gun a weapon id is, in words (owner, 2 Nov 2026, inbox #468: "You also need to find out what exact weapons
they are using nd not just the codes they are showing").

The debugger log names a kill's weapon by number (``OnGameAchievementNotify ... weapon:N``), and AFC Capture sends a
player's most-used weapon as that number ("9"). Before this module the site stored and printed the number, so the
leaderboard editor, the overlays and the leaderboard graphics showed "9" where the game showed a Desert Eagle.

THE RULE, one place for the whole site (R24), the same names AFC Capture's dashboard prints:
  1. an admin's own name in /admin/ (GameWeapon), when the admin wrote one: a row whose name is one a machine
     wrote (the current table's, a retired one, or the unknown placeholder) is a seeded row, not an admin's name;
  2. else the name the game shows its players (weapon_names.WEAPON_NAMES, generated by
     afc-capture/dev/build_weapons.py from the client's own English text, owner 3 Nov 2026, inbox #474: "EVO3 and
     SeaGull are not the actual names of the guns please");
  3. else "unknown gun (id N)", never a bare number and never an internal label.
A negative id (zone, fall, bleed-out), an empty value or garbage is no gun: "". A value that is already a name is
kept as it is, so naming twice changes nothing; "unknown gun (id N)" is read back as N, and so is a name an older
table wrote (weapon_names_retired.RETIRED_NAMES: "EVO3" -> 814, "BLT" -> 45), so a stored row is renamed by the
next `manage.py seed_game_weapons`.

CONNECTS TO: capture_rich_stats.apply_capture_rich_stats (the map upload) and live_ranking.normalize_live_standings
(the live push) store and serve the NAME; management/commands/seed_game_weapons.py names rows stored before this
module existed; views_kill_feed names the sniper weapons. Mirror of afc-capture/afc_capture/weapons.py.
"""
import re

from .weapon_names import WEAPON_NAMES
from .weapon_names_retired import RETIRED_NAMES

UNKNOWN = "unknown gun (id {})"
_UNKNOWN_RE = re.compile(r"^unknown gun \(id (\d+)\)$")


_VERSION_RE = re.compile(r"(?: \([^)]*\))?$")
_LEVEL_RE = re.compile(r"-(?:I{1,3}|X|Y)$")


def gun_of(name):
    """The gun a version is named after: "AWM-Y" -> "AWM", "Kar98k-III (Droid Apocalypse)" -> "Kar98k",
    "M24-I" -> "M24", "M249-X" -> "M249" (a machine gun, not the M24). A hyphen that is part of the gun's own name
    stays: "MAG-7 (Droid Apocalypse)" -> "MAG-7", "FGL-24" -> "FGL-24" (the first version of this cut at the first
    hyphen, so the old "MAG7" rows matched no gun, found on the production dry run of 3 Nov 2026). A version is the
    game's level suffix (-I, -II, -III, -X, -Y) and / or a bracketed mode name. Read by kill_feed (the sniper set)."""
    return _LEVEL_RE.sub("", _VERSION_RE.sub("", (name or "").strip())).strip()


def _retired_ids():
    """A retired name -> the id a stored row carrying it stands for.
    - one id ever had it ("EVO3" was only 814): that id;
    - several ids had it but they are all versions of one gun ("BLT" was 45 and 173, both M82B; "Gold MP5" was the
      three gold MP5 levels): the gun itself (the id whose current name is exactly that gun), since the row does
      not say which version;
    - otherwise, or when the name is some gun's current name ("M249" is the 19 today, it was also the 71): not
      mapped, the row keeps its value."""
    owners = {}
    for weapon_id, names in RETIRED_NAMES.items():
        for name in names:
            owners.setdefault(name, set()).add(weapon_id)
    current = set(WEAPON_NAMES.values())
    by_name = {}
    for weapon_id, name in sorted(WEAPON_NAMES.items()):
        by_name.setdefault(name, weapon_id)          # the lowest id of a name is the gun itself
    out = {}
    for name, ids in owners.items():
        if name in current:
            continue
        if len(ids) == 1:
            out[name] = next(iter(ids))
            continue
        guns = {gun_of(WEAPON_NAMES.get(i, "")) for i in ids}
        if len(guns) == 1 and next(iter(guns)) in by_name:
            out[name] = by_name[next(iter(guns))]
    return out


RETIRED_IDS = _retired_ids()


def weapon_id_of(value):
    """The weapon id a stored or pushed value stands for, or None when it is not an id: 9 / "9" / " 9 " -> 9,
    "unknown gun (id 814)" -> 814, a retired machine name "EVO3" -> 814, "Desert Eagle" / "" / None / "-3" ->
    None."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value if value >= 0 else None
    text = str(value or "").strip()
    if text.isdigit():
        return int(text)
    unknown = _UNKNOWN_RE.match(text)
    if unknown:
        return int(unknown.group(1))
    return RETIRED_IDS.get(text)


def admin_names():
    """{weapon_id: name} for every GameWeapon row whose name an admin wrote, in ONE query, so a caller naming
    many values (a live push every ~2 s, a map upload) loads it once. Rows still carrying a name a machine wrote
    (the current table's, a retired one, the unknown placeholder) are left out: they say nothing the table does
    not."""
    from .models import GameWeapon

    names = {}
    for weapon_id, name in GameWeapon.objects.values_list("weapon_id", "name"):
        name = (name or "").strip()
        if name and not is_machine_name(weapon_id, name):
            names[weapon_id] = name
    return names


def is_machine_name(weapon_id, name):
    """True when `name` is one a script wrote for this id, never an admin: the current table's name, a name an
    older table gave it (RETIRED_NAMES) or the unknown placeholder. Read by admin_names and seed_game_weapons."""
    return name in (WEAPON_NAMES.get(weapon_id), UNKNOWN.format(weapon_id)) or name in RETIRED_NAMES.get(weapon_id, ())


def weapon_label(value, names=None):
    """The name to store and show for a weapon value. See the module docstring for the order. `names` is an
    admin_names() map the caller already loaded; without it this loads one."""
    weapon_id = weapon_id_of(value)
    if weapon_id is None:
        if isinstance(value, bool):
            return ""
        text = str(value or "").strip()
        # a name stays a name; a negative number or a bare minus is no gun
        return "" if not text or text.lstrip("-").isdigit() else text
    if names is None:
        names = admin_names()
    return names.get(weapon_id) or WEAPON_NAMES.get(weapon_id) or UNKNOWN.format(weapon_id)
