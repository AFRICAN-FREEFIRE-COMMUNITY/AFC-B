"""What gun a weapon id is, in words (owner, 2 Nov 2026, inbox #468: "You also need to find out what exact weapons
they are using nd not just the codes they are showing").

The debugger log names a kill's weapon by number (``OnGameAchievementNotify ... weapon:N``), and AFC Capture sends a
player's most-used weapon as that number ("9"). Before this module the site stored and printed the number, so the
leaderboard editor, the overlays and the leaderboard graphics showed "9" where the game showed a Desert Eagle.

THE RULE, one place for the whole site (R24), the same names AFC Capture's dashboard prints:
  1. an admin's own name in /admin/ (GameWeapon), when the admin wrote one: a row whose name is still the
     kill_feed.KNOWN_WEAPONS seed text ("SVD (marksman, not counted)") is a seeded row, not an admin's name, so
     the award notes never reach an overlay;
  2. else the enum name (weapon_names.WEAPON_NAMES, 252 ids, generated by afc-capture/dev/build_weapons.py);
  3. else the name the game's own replay file gives the id (REPLAY_NAMES below);
  4. else "unknown gun (id N)", never a bare number.
A negative id (zone, fall, bleed-out), an empty value or garbage is no gun: "". A value that is already a name is
kept as it is, so naming twice changes nothing; "unknown gun (id N)" is read back as N, so a gun an admin names
later is picked up by the next `manage.py seed_game_weapons`.

CONNECTS TO: capture_rich_stats.apply_capture_rich_stats (the map upload) and live_ranking.normalize_live_standings
(the live push) store and serve the NAME; management/commands/seed_game_weapons.py names rows stored before this
module existed; views_kill_feed names the sniper weapons. Mirror of afc-capture/afc_capture/weapons.py.
"""
import re

from .weapon_names import WEAPON_NAMES

UNKNOWN = "unknown gun (id {})"
_UNKNOWN_RE = re.compile(r"^unknown gun \(id (\d+)\)$")

# ── ids the enum does not list, named by the game itself (3 Nov 2026, inbox #468) ─────────────────────────
# The head of a match's replay .bin (Free Fire_64_Data/Replays) carries the config records of the guns that
# match's mode overrides: the bytes 02 94 02, the id as text, the game's internal name, then its HUD icon, sound
# and animation keys. Read from the 69 AFC replays on the observer PC (WEBSITE/tasks/weapon-ids-and-replay-
# 2026-11-03/). 814 is the most used gun in those matches (2,485 of 17,204 kill events): an SMG by its animation
# set (MP5) and its kills (median 5.2 m, the SMG range). 812 uses the AWM's bolt sound and animation: a bolt
# action sniper, NOT counted for the sniper award until the owner says so. These are the game's internal names;
# an admin's name in /admin/ wins over them. AFC Capture 1.5.2 does not carry them yet (its table is the enum).
REPLAY_NAMES = {
    149: "Throwing Knife",
    812: "SeaGull",
    814: "EVO3",
    30805: "SeaGull (Storm)",
    30806: "EVO3 (FFWS Storm)",
    30907: "EVO3 (Blood Bat Lv1)",
    30909: "SeaGull (Blood Bat Lv1)",
}


def weapon_id_of(value):
    """The weapon id a stored or pushed value stands for, or None when it is not an id: 9 / "9" / " 9 " -> 9,
    "unknown gun (id 814)" -> 814, "Desert Eagle" / "" / None / "-3" -> None."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value if value >= 0 else None
    text = str(value or "").strip()
    if text.isdigit():
        return int(text)
    unknown = _UNKNOWN_RE.match(text)
    return int(unknown.group(1)) if unknown else None


def admin_names():
    """{weapon_id: name} for every GameWeapon row whose name an admin wrote, in ONE query, so a caller naming
    many values (a live push every ~2 s, a map upload) loads it once. Rows still carrying the seed text, the
    enum name or the unknown placeholder are left out: they say nothing the enum does not."""
    from .kill_feed import KNOWN_WEAPONS
    from .models import GameWeapon

    names = {}
    for weapon_id, name in GameWeapon.objects.values_list("weapon_id", "name"):
        name = (name or "").strip()
        if name and name not in (KNOWN_WEAPONS.get(weapon_id, (None,))[0], WEAPON_NAMES.get(weapon_id),
                                 REPLAY_NAMES.get(weapon_id), UNKNOWN.format(weapon_id)):
            names[weapon_id] = name
    return names


def weapon_label(value, names=None):
    """The name to store and show for a weapon value. See the module docstring for the order. `names` is an
    admin_names() map the caller already loaded; without it this loads one."""
    weapon_id = weapon_id_of(value)
    if weapon_id is None:
        if isinstance(value, bool):
            return ""
        text = str(value or "").strip()
        # a name stays a name; a negative number or a bare minus is no gun
        return "" if not text or text.lstrip("-").isdigit() else text
    if names is None:
        names = admin_names()
    return (names.get(weapon_id) or WEAPON_NAMES.get(weapon_id) or REPLAY_NAMES.get(weapon_id)
            or UNKNOWN.format(weapon_id))
