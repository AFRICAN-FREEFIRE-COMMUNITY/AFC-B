"""python manage.py seed_game_weapons [--dry-run]

Two jobs, both idempotent, run once after a deploy that changes the weapon table:

1. Fills the kill feed's GameWeapon table (inbox #350, the sniper award; #468, every gun by name). First the ids
   kill_feed.KNOWN_WEAPONS proved against the debugger log (WEBSITE/tasks/kill-feed-weapon-ids-2026-10-24/), with
   their sniper ticks; then every other id of the game's enum (weapon_names.WEAPON_NAMES, 252 ids, generated by
   afc-capture/dev/build_weapons.py) and the ids named by the game's replay files (weapons.REPLAY_NAMES: 814
   EVO3, 812 SeaGull ...) as not a sniper. It never overwrites a row an admin already has: a weapon that exists
   keeps its name and its "is sniper" tick.
2. Names the most-used weapon stored on player rows before the site named it (inbox #468, 3 Nov 2026): a bare id
   ("9") or "unknown gun (id N)" becomes the gun's name through weapons.weapon_label, so a gun an admin names in
   /admin/ later reaches old rows on the next run. A value that is already a name is left alone.

The kill-stats view uses the same defaults while the table is still empty.
"""
from django.core.management.base import BaseCommand
from django.db.models import Q

from afc_tournament_and_scrims.kill_feed import KNOWN_WEAPONS
from afc_tournament_and_scrims.models import GameWeapon, TournamentPlayerMatchStats
from afc_tournament_and_scrims.weapon_names import WEAPON_NAMES
from afc_tournament_and_scrims.weapons import REPLAY_NAMES, admin_names, weapon_id_of, weapon_label


class Command(BaseCommand):
    help = "Fill GameWeapon from the proven ids and the game's enum, and name stored most-used weapons."

    def add_arguments(self, parser):
        parser.add_argument("--dry-run", action="store_true", help="Say what would change, change nothing.")

    def handle(self, *args, **options):
        dry = options["dry_run"]

        # ── 1. the weapon table: proven ids first (their names and sniper ticks win), then the enum ──
        have = set(GameWeapon.objects.values_list("weapon_id", flat=True))
        rows = dict((wid, (name, sniper)) for wid, (name, sniper) in KNOWN_WEAPONS.items())
        for wid, name in list(WEAPON_NAMES.items()) + list(REPLAY_NAMES.items()):
            rows.setdefault(wid, (name, False))
        new = [(wid, name, sniper) for wid, (name, sniper) in sorted(rows.items()) if wid not in have]
        for wid, name, sniper in new:
            self.stdout.write(f"{'would add' if dry else 'add'} {wid} {name} sniper={sniper}")
        if not dry:
            GameWeapon.objects.bulk_create(
                [GameWeapon(weapon_id=wid, name=name, is_sniper=sniper) for wid, name, sniper in new])
        self.stdout.write(f"{len(new)} new, {len(have)} kept as they were")

        # ── 2. stored most-used weapons that are still a code ──
        names = admin_names()
        coded = (TournamentPlayerMatchStats.objects
                 .filter(Q(most_used_weapon__regex=r"^[0-9]+$") | Q(most_used_weapon__startswith="unknown gun (id "))
                 .values_list("most_used_weapon", flat=True).distinct())
        renamed = 0
        for value in sorted(set(coded)):    # one UPDATE per distinct code, not one per row
            if weapon_id_of(value) is None:
                continue
            label = weapon_label(value, names)
            if label == value:
                continue                    # still unknown, nothing new to say
            same = TournamentPlayerMatchStats.objects.filter(most_used_weapon=value)
            count = same.count() if dry else same.update(most_used_weapon=label)
            renamed += count
            self.stdout.write(f"{'would name' if dry else 'named'} {value!r} -> {label!r} on {count} rows")
        self.stdout.write(f"{renamed} stored most-used weapons {'would be ' if dry else ''}named")
